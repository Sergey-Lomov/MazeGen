/// Narration-level events for Wilson's algorithm (see GitHub issue #145). Wilson's decision shape
/// is a two-level loop — an outer "pick an unvisited node and loop-erased-random-walk from it"
/// iteration, and an inner per-step random walk that can erase its own loops — so the event set
/// mirrors both levels, unlike Kruskal's single-level per-edge decision.
///
/// Wire tags, `EncodeEventPayload`, and `DebugEvent::is_mutating` are generated by `codegen` (see
/// `toasty-honking-pie.md`) from the `#[wire(...)]` attributes below, into the sibling
/// `wilson_wire.rs` — never hand-edit that file, edit the attributes here instead.
#[derive(Debug, Clone, PartialEq, maze_core_macros::WireEvent)]
pub enum WilsonEvent {
    /// The maze's start node is seeded into `visited` before the first walk even picks a
    /// `walk_start` — the algorithm's actual first operation, emitted once at the root scope (not
    /// nested under any `"walk N"` scope, since no walk is running yet). Preset-connected nodes are
    /// *not* covered by this event: they're seeded the same way presets are seeded everywhere else
    /// in this codebase (a silent zero-state snapshot, not narrated events) — only the start node's
    /// seeding is a distinct, narratable algorithm step.
    #[wire(tag = 7, mutating, name = "id")]
    StartVisited(NodeId),
    /// The unvisited node a new loop-erased random walk starts from, chosen uniformly at random
    /// from the current unvisited set. Emitted first in every `"walk N"` scope, directly under it
    /// (not nested in `"search"`/`"commit"`), so a narration reader knows the walk's origin before
    /// either sub-phase starts.
    #[wire(tag = 1, mutating, name = "id")]
    WalkStartPicked(NodeId),
    /// One step of the walk: the RNG chose `to` as the next cell from `from`'s connectable
    /// neighbors. Emitted under the walk's `"search"` sub-scope — every step-related event
    /// (`StepTaken`/`LoopErased`/`WalkDeadEnd`) lives there flat, not one `"step M"` sub-scope per
    /// step: a step is usually a single event, so a scope per step added tree depth without adding
    /// information (GitHub issue #145's follow-up).
    #[wire(tag = 2, mutating)]
    StepTaken { from: NodeId, to: NodeId },
    /// The walk stepped onto a node it had already visited earlier in this same walk (before
    /// reaching a node already part of the maze) — the loop between the earlier visit and now is
    /// erased by overwriting `next[node]` with the new outgoing step. Carries no fields beyond
    /// `node`: the preceding `StepTaken` (same `"search"` sub-scope) already states which node was
    /// re-entered (`StepTaken.to`), so duplicating `from`/`to` here would be redundant.
    #[wire(tag = 3, mutating)]
    LoopErased { node: NodeId },
    /// The walk's current node has no connectable neighbors — the walk stops here without
    /// reaching an already-visited node. The last event in the walk's `"search"` sub-scope, in
    /// place of a further `StepTaken`. The `"commit"` sub-scope still runs against whatever partial
    /// path was recorded before the dead end.
    #[wire(tag = 4)]
    WalkDeadEnd,
    /// An edge was added between `from` and `to` while committing the loop-erased path into the
    /// maze. Emitted under the walk's `"commit"` sub-scope. `bidirectional` records whether the
    /// passage opened in both directions (Wilson always adds both when
    /// `try_add_bidirectional_edge` succeeds) — carried explicitly so replay consumers don't have
    /// to assume it.
    #[wire(tag = 5, mutating)]
    EdgeAdded {
        from: NodeId,
        to: NodeId,
        bidirectional: bool,
    },
    /// A node was marked as part of the maze while committing the loop-erased path. Emitted under
    /// the walk's `"commit"` sub-scope.
    #[wire(tag = 6, mutating, name = "id")]
    NodeVisited(NodeId),
}

pub const VISITED: &str = "visited";
pub const CURRENT_WALK: &str = "current_walk";
pub const WALK_START: &str = "walk_start";
pub const WALK_HEAD: &str = "walk_head";

/// `visited` — a plain `Region` set, insert-only, mirroring the algorithm's own
/// `visited: HashSet<NodeId>` exactly (a node is never un-visited once committed).
impl DebugValueDelta<NodeId> for WilsonEvent {
    fn debug_value_deltas(&self) -> Vec<(&'static str, DebugValueOp, NodeId)> {
        match self {
            WilsonEvent::StartVisited(id) | WilsonEvent::NodeVisited(id) => {
                vec![(VISITED, DebugValueOp::Insert, *id)]
            }
            _ => Vec::new(),
        }
    }
}

/// `current_walk` — the walk's `next` map (GitHub issue #145's follow-up), a `DebugValueKind::Map`
/// value: `StepTaken { from, to }` sets `next[from] = to`, overwriting any prior value for `from`
/// exactly the way `HashMap::insert` does (this is why `current_walk` can't be a plain
/// `DebugValueDelta` — `Insert`/`Remove` only ever touch one id, never overwrite a key's value).
/// `WalkStartPicked` clears the map — a new walk starts with an empty `next`, so the previous
/// walk's (already-committed-or-abandoned) track doesn't linger into the new one's replay.
/// `LoopErased` needs no delta of its own: it's emitted immediately after the `StepTaken` that
/// already performed the overwrite, purely to narrate that this particular overwrite erased a
/// loop — the map state is already correct by the time `LoopErased` is emitted.
impl DebugMapDelta<NodeId> for WilsonEvent {
    fn debug_map_deltas(&self) -> Vec<(&'static str, DebugMapOp<NodeId>)> {
        match self {
            WilsonEvent::WalkStartPicked(_) => vec![(CURRENT_WALK, DebugMapOp::Clear)],
            WilsonEvent::StepTaken { from, to } => {
                vec![(CURRENT_WALK, DebugMapOp::Set(*from, *to))]
            }
            _ => Vec::new(),
        }
    }
}

/// `walk_start`/`walk_head` (GitHub issue #145's follow-up) — `DebugValueKind::Vertex` values.
/// Replaced these with a dedicated `Vertex` kind instead of reading the endpoints off
/// `current_walk`'s `Map` on the web side: `current_walk` preserves insertion order for its keys
/// (a `HashMap::insert`-style overwrite of an existing key doesn't move it), so "last key" isn't
/// reliably "most recently stepped-from" once a walk revisits a node via loop erasure — a
/// structurally unsound heuristic. These two are reported directly by the events that actually
/// change them instead.
///
/// `walk_start` — the current walk's origin: `Set` once per walk at `WalkStartPicked`, holding
/// steady for the rest of that walk (no `Clear` needed between walks — the next `WalkStartPicked`
/// simply overwrites it).
///
/// `walk_head` — the walk's current position: `Set` to the origin at `WalkStartPicked` (before any
/// step, the head *is* the start), then to `to` at every `StepTaken` as the walk advances.
impl DebugVertexDelta<NodeId> for WilsonEvent {
    fn debug_vertex_deltas(&self) -> Vec<(&'static str, DebugVertexOp<NodeId>)> {
        match self {
            WilsonEvent::WalkStartPicked(node) => vec![
                (WALK_START, DebugVertexOp::Set(*node)),
                (WALK_HEAD, DebugVertexOp::Set(*node)),
            ],
            WilsonEvent::StepTaken { to, .. } => vec![(WALK_HEAD, DebugVertexOp::Set(*to))],
            _ => Vec::new(),
        }
    }
}

/// Static declaration of Wilson's debug values (GitHub issue #131, extended by #145's follow-up
/// for `current_walk`/`walk_start`/`walk_head`) — mirrors `recursive_backtracker::debug_value_names()`.
/// A static property of the algorithm, not derived from what a particular run happened to emit
/// (see that function's doc comment for why).
pub fn debug_value_names() -> &'static [(&'static str, DebugValueKind)] {
    &[
        (VISITED, DebugValueKind::Region),
        (CURRENT_WALK, DebugValueKind::Map),
        (WALK_START, DebugValueKind::Vertex),
        (WALK_HEAD, DebugValueKind::Vertex),
    ]
}

/// Groups every node into a field-geometric connected component (geometric `split_aware_neighbors`
/// plus preset-teleport edges in both directions, mirroring the search-phase candidate pool the
/// walk itself uses) computed once up front, before any walk runs. A loop-erased random walk can
/// only ever reach `visited` by stepping through candidates from this same pool — a walk started
/// inside a component with no visited node yet would wander forever if that component happens to
/// have no dead end (GitHub issue #417's restart problem applies to Wilson too, but naively
/// seeding an arbitrary unvisited node and letting the ordinary walk loop retry is not safe here
/// the way it is for `CustomVertexBased`/`RecursiveBacktracker`: nothing bounds how long a walk
/// inside an unreachable, dead-end-free component would run). Precomputing components lets the
/// main loop tell "still-reachable, just not yet walked" apart from "genuinely a separate
/// component" without ever starting a doomed walk.
fn compute_components<T: Tessellation>(
    graph: &Graph,
    field: &MultiLevelField<T>,
    all_nodes: &[NodeId],
    preset_state: &PresetState,
) -> HashMap<NodeId, usize> {
    let mut teleport_srcs: HashMap<NodeId, Vec<NodeId>> = HashMap::new();
    for (&src, dsts) in &preset_state.preset_teleports {
        for &dst in dsts {
            teleport_srcs.entry(dst).or_default().push(src);
        }
    }

    let mut component_of: HashMap<NodeId, usize> = HashMap::new();
    let mut next_component = 0usize;
    for &root in all_nodes {
        if component_of.contains_key(&root) {
            continue;
        }
        let mut stack = vec![root];
        component_of.insert(root, next_component);
        while let Some(node) = stack.pop() {
            let teleport_dsts = preset_state
                .preset_teleports
                .get(&node)
                .map(Vec::as_slice)
                .unwrap_or(&[]);
            let teleport_reverse_srcs = teleport_srcs.get(&node).map(Vec::as_slice).unwrap_or(&[]);
            let neighbors = split_aware_neighbors(field, graph, node)
                .into_iter()
                .chain(teleport_dsts.iter().copied())
                .chain(teleport_reverse_srcs.iter().copied());
            for n in neighbors {
                if component_of.contains_key(&n) {
                    continue;
                }
                component_of.insert(n, next_component);
                stack.push(n);
            }
        }
        next_component += 1;
    }
    component_of
}

pub fn generate<T: Tessellation>(
    graph: &mut Graph,
    field: &MultiLevelField<T>,
    seed: u64,
    start: NodeId,
    preset_state: &PresetState,
    mut event_log: Option<&mut EventLog<WilsonEvent>>,
) {
    let all_nodes: Vec<NodeId> = graph.nodes().map(|n| n.id).collect();
    let component_of = compute_components(graph, field, &all_nodes, preset_state);
    let mut visited: HashSet<NodeId> = HashSet::new();
    let mut rng = MazeRng::seed_from_u64(seed);

    // Reverse index of `preset_teleports`: for a one-way preset teleport `src -> dst`, `dst` has
    // no forward path back through it, so a walk that enters `dst`'s side first could never reach
    // `visited` at all (GitHub issue #228). The teleport edge already exists in the graph
    // regardless of which direction the walk uses it to search, so it's safe to let the walk step
    // `dst -> src` here too — only the *search* direction is relaxed; `is_preset_teleport` below
    // still recognizes this pair and skips re-adding the edge.
    let mut teleport_srcs: HashMap<NodeId, Vec<NodeId>> = HashMap::new();
    for (&src, dsts) in &preset_state.preset_teleports {
        for &dst in dsts {
            teleport_srcs.entry(dst).or_default().push(src);
        }
    }

    // Preset-connected nodes are a zero-state snapshot, not a narrated algorithm step — silent,
    // like everywhere else in this codebase.
    for &pc in &preset_state.preset_connected {
        visited.insert(pc);
    }
    // Seeding `start` into `visited` *is* the algorithm's actual first operation — narrated at
    // root, before any `"walk N"` scope (no walk has picked a `walk_start` yet).
    visited.insert(start);
    if let Some(log) = event_log.as_deref_mut() {
        log.emit(WilsonEvent::StartVisited(start));
    }

    let mut unvisited: Vec<NodeId> = all_nodes
        .iter()
        .copied()
        .filter(|&n| !visited.contains(&n))
        .collect();
    let mut visited_components: HashSet<usize> = visited
        .iter()
        .filter_map(|n| component_of.get(n).copied())
        .collect();

    while !unvisited.is_empty() {
        // Only a node whose component already contains a visited node can safely be walked from —
        // the walk can only ever stop by reaching `visited`, so a walk started in a
        // not-yet-reachable component would never terminate if that component has no dead end (see
        // `compute_components`'s doc comment). Pick randomly among such candidates; if none exist,
        // every remaining unvisited node belongs to a genuinely separate component — seed one
        // directly into `visited` (GitHub issue #417's restart, mirroring `CustomVertexBased`'s
        // `StartVisited` reuse) instead of attempting a walk, which makes its whole component
        // walkable from then on.
        //
        // `walkable` scans all of `unvisited` — already the same order of cost as the pre-existing
        // `unvisited.retain(...)` below (each successful walk already did an O(n) scan to drop its
        // visited nodes), so this doesn't change the loop's asymptotic behavior, only its constant.
        let walkable: Vec<usize> = unvisited
            .iter()
            .enumerate()
            .filter(|(_, n)| {
                component_of
                    .get(n)
                    .is_some_and(|c| visited_components.contains(c))
            })
            .map(|(i, _)| i)
            .collect();
        let walk_start = if walkable.is_empty() {
            let pick_idx = rng.random_range(0..unvisited.len());
            let new_root = unvisited.swap_remove(pick_idx);
            visited.insert(new_root);
            if let Some(c) = component_of.get(&new_root) {
                visited_components.insert(*c);
            }
            if let Some(log) = event_log.as_deref_mut() {
                log.emit(WilsonEvent::StartVisited(new_root));
            }
            continue;
        } else {
            unvisited[walkable[rng.random_range(0..walkable.len())]]
        };

        let mut walk_scope = event_log
            .as_deref_mut()
            .map(|log| log.enter_numbered("walk"));
        if let Some(g) = walk_scope.as_mut() {
            g.emit(WilsonEvent::WalkStartPicked(walk_start));
        }

        // Loop-erased random walk until we hit a visited node.
        // next[node] = the node we stepped to from node during the walk.
        let mut next: HashMap<NodeId, NodeId> = HashMap::new();
        let mut current = walk_start;
        {
            // Scoped block: the "search" child guard must drop before `walk_scope` is used again
            // below (the commit phase) — `ScopeGuard` has a non-trivial `Drop`, so NLL won't
            // shorten its borrow to its last use.
            let mut search_scope = walk_scope.as_mut().map(|g| g.enter("search"));
            loop {
                let teleport_dsts = preset_state
                    .preset_teleports
                    .get(&current)
                    .map(Vec::as_slice)
                    .unwrap_or(&[]);
                let teleport_reverse_srcs = teleport_srcs
                    .get(&current)
                    .map(Vec::as_slice)
                    .unwrap_or(&[]);
                // Preset-teleport destinations already have their edge in the graph —
                // traversable regardless of `bidirectional_edge_feasible` (see GitHub issue #226).
                // The reverse of a one-way preset teleport is also traversable for search purposes,
                // so a walk can still reach `visited` from the "wrong" side (see `teleport_srcs`
                // above, #228).
                //
                // `bidirectional_edge_feasible` (both directions free), not `can_connect` (either
                // direction free) — Wilson always commits a full bidirectional passage via
                // `try_add_bidirectional_edge` in the commit phase below. `can_connect`'s looser
                // check let a one-direction-blocked candidate pass this search-phase filter, get
                // walked into and committed, yet have `try_add_bidirectional_edge` silently refuse
                // to add anything — leaving `EdgeAdded`/`NodeVisited` narrated with no graph edge
                // behind them.
                let neighbors: Vec<NodeId> = split_aware_neighbors(field, graph, current)
                    .into_iter()
                    .filter(|&n| bidirectional_edge_feasible(preset_state, current, n))
                    .chain(teleport_dsts.iter().copied())
                    .chain(teleport_reverse_srcs.iter().copied())
                    .collect();

                let dead_end = if neighbors.is_empty() {
                    if let Some(g) = search_scope.as_mut() {
                        g.emit(WilsonEvent::WalkDeadEnd);
                    }
                    true
                } else {
                    let chosen = neighbors[rng.random_range(0..neighbors.len())];
                    if let Some(g) = search_scope.as_mut() {
                        g.emit(WilsonEvent::StepTaken {
                            from: current,
                            to: chosen,
                        });
                    }
                    let erased_loop = next.contains_key(&chosen);
                    next.insert(current, chosen);
                    if erased_loop {
                        if let Some(g) = search_scope.as_mut() {
                            g.emit(WilsonEvent::LoopErased { node: chosen });
                        }
                    }
                    if visited.contains(&chosen) {
                        true
                    } else {
                        current = chosen;
                        false
                    }
                };
                if dead_end {
                    break;
                }
            }
        }

        // Commit the loop-erased path: walk from walk_start following next[] until visited.
        // Only opens the "commit" scope when there's actually a path to commit — a walk that
        // dead-ends on its very first step (no `next` entry recorded for `walk_start`) would
        // otherwise leave an empty, non-expandable "commit" scope in the tree.
        let has_path_to_commit = next.contains_key(&walk_start);
        if !visited.contains(&walk_start) && has_path_to_commit {
            let mut commit_scope = walk_scope.as_mut().map(|g| g.enter("commit"));
            let mut node = walk_start;
            while !visited.contains(&node) {
                let Some(&dst) = next.get(&node) else {
                    break;
                };
                // A preset-teleport step already has its edge in the graph — skip adding it again,
                // whether the walk used it forward (`node -> dst`) or, for a one-way teleport,
                // backward through the reverse side (`dst -> node`, see `teleport_srcs` above).
                let is_preset_teleport = preset_state
                    .preset_teleports
                    .get(&node)
                    .is_some_and(|dsts| dsts.contains(&dst))
                    || preset_state
                        .preset_teleports
                        .get(&dst)
                        .is_some_and(|dsts| dsts.contains(&node));
                if !is_preset_teleport {
                    try_add_bidirectional_edge(graph, node, dst, preset_state);
                }
                visited.insert(node);
                if let Some(g) = commit_scope.as_mut() {
                    g.emit(WilsonEvent::EdgeAdded {
                        from: node,
                        to: dst,
                        bidirectional: true,
                    });
                    g.emit(WilsonEvent::NodeVisited(node));
                }
                node = dst;
            }
        }

        // A walk that dead-ended without ever reaching `visited` (no path exists from `walk_start`
        // under the current edge constraints — e.g. every neighbor is one-directionally blocked for
        // the bidirectional add this algorithm always performs) leaves `walk_start` neither visited
        // nor removed from `unvisited` by the `retain` below. Without this, the outer `while
        // !unvisited.is_empty()` loop would pick the exact same unreachable `walk_start` forever —
        // an infinite loop (confirmed: `next`'s loop-erasure can't break it, since the walk keeps
        // re-stepping between the same disconnected node(s) with no progress). `walk_start` is
        // dropped from the pool unconnected, same as it would end up for a fully preset-isolated
        // node — reachability/connectivity here is `build_maze`'s repair pass's concern, not this
        // algorithm's.
        if !visited.contains(&walk_start) && !has_path_to_commit {
            unvisited.retain(|&n| n != walk_start);
        }

        unvisited.retain(|n| !visited.contains(n));
    }
}
