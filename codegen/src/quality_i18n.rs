//! Enumerates every check/strategy/rule-param/issue id via native (non-wasm) calls into
//! `maze-wasm`'s catalog getters — see GitHub issue #361. Emits a generated TS file listing every
//! known id as a const array, for `qualityI18n.ts`'s hand-written registries to complete against.

use std::collections::BTreeSet;

pub struct QualityIds {
    pub check_ids: BTreeSet<String>,
    pub strategy_ids: BTreeSet<String>,
    pub rule_param_ids: BTreeSet<String>,
    pub issue_kind_ids: BTreeSet<String>,
    pub param_ids: BTreeSet<String>,
}

pub fn discover() -> QualityIds {
    let checks = maze_wasm::checks_catalog::available_checks_list();
    let strategies = maze_wasm::strategies_catalog::available_strategies_list();
    let rule_params = maze_wasm::check_descriptor::rule_params_list();

    let mut check_ids = BTreeSet::new();
    let mut issue_kind_ids = BTreeSet::new();
    let mut param_ids = BTreeSet::new();
    for c in &checks {
        check_ids.insert(c.id.to_string());
        for k in &c.issue_kinds {
            issue_kind_ids.insert(k.to_string());
        }
        for p in &c.params {
            param_ids.insert(p.id.to_string());
        }
    }

    let mut strategy_ids = BTreeSet::new();
    for s in &strategies {
        strategy_ids.insert(s.id.to_string());
        issue_kind_ids.insert(s.handles.to_string());
        for p in &s.params {
            param_ids.insert(p.id.to_string());
        }
    }

    let mut rule_param_ids = BTreeSet::new();
    for p in &rule_params {
        rule_param_ids.insert(p.id.to_string());
    }

    QualityIds {
        check_ids,
        strategy_ids,
        rule_param_ids,
        issue_kind_ids,
        param_ids,
    }
}

pub fn generate_ts_file(ids: &QualityIds) -> String {
    let mut out = String::new();
    out.push_str("// @generated by codegen/ — DO NOT EDIT. Source: maze-wasm's checks_catalog/strategies_catalog/check_descriptor.\n\n");
    emit_const(&mut out, "CHECK_IDS", &ids.check_ids);
    emit_const(&mut out, "STRATEGY_IDS", &ids.strategy_ids);
    emit_const(&mut out, "RULE_PARAM_IDS", &ids.rule_param_ids);
    emit_const(&mut out, "ISSUE_KIND_IDS", &ids.issue_kind_ids);
    emit_const(&mut out, "PARAM_IDS", &ids.param_ids);
    out
}

fn emit_const(out: &mut String, name: &str, ids: &BTreeSet<String>) {
    out.push_str(&format!("export const {name} = [\n"));
    for id in ids {
        out.push_str(&format!("  \"{id}\",\n"));
    }
    out.push_str("] as const;\n\n");
}

/// One entry per (registry name, missing id) — surfaced by `codegen --check` as a hard error, and
/// by a plain `cargo run -p codegen` as a warning (never auto-appended: a skeleton entry with
/// fabricated label/description text would be worse than an explicit gap, since nothing forces a
/// human to revisit a silently-inserted placeholder).
pub struct MissingEntry {
    pub registry: &'static str,
    pub id: String,
}

/// Diffs `ids` against the id keys already present as object literal keys in `qualityI18n_source`
/// — a plain text scan (`"<id>: {"` or `<id>: {`), not a TS parse, mirrors `check.rs`'s own
/// text-scanning precedent (`old_write_call_sequence`) for reading a sibling-language file without
/// pulling in a TS parser.
pub fn find_missing(ids: &QualityIds, qualityi18n_source: &str) -> Vec<MissingEntry> {
    let mut missing = Vec::new();
    collect_missing(
        &mut missing,
        "checkI18n",
        &ids.check_ids,
        qualityi18n_source,
    );
    collect_missing(
        &mut missing,
        "strategyI18n",
        &ids.strategy_ids,
        qualityi18n_source,
    );
    collect_missing(
        &mut missing,
        "issueI18n",
        &ids.issue_kind_ids,
        qualityi18n_source,
    );
    collect_missing(
        &mut missing,
        "paramI18n",
        &ids.param_ids,
        qualityi18n_source,
    );
    missing
}

fn collect_missing(
    out: &mut Vec<MissingEntry>,
    registry: &'static str,
    ids: &BTreeSet<String>,
    source: &str,
) {
    let Some(registry_start) = source.find(&format!("export const {registry}")) else {
        // Registry object itself not found — every id is trivially "missing", but that almost
        // certainly means the registry was renamed, not that every entry was deleted; report
        // nothing rather than a wall of false positives that would mask the real problem.
        return;
    };
    let registry_body_end = source[registry_start..]
        .find("\n};")
        .map(|i| registry_start + i)
        .unwrap_or(source.len());
    let registry_body = &source[registry_start..registry_body_end];
    for id in ids {
        let key_present = registry_body.contains(&format!("\n  {id}:"))
            || registry_body.contains(&format!("\n  \"{id}\":"));
        if !key_present {
            out.push(MissingEntry {
                registry,
                id: id.clone(),
            });
        }
    }
}

/// Diffs `ids.check_ids` against `DETAIL_LABELS`/`DETAIL_DESCRIPTIONS` object literal keys in
/// `issue_registry_source` (`maze-web/src/components/issueRegistry.ts`) — same text-scan approach
/// as `find_missing`/`collect_missing`, and same registry/id shape (`MissingEntry`) so
/// `codegen --check`'s reporting path treats a gap here identically to a `qualityI18n.ts` gap
/// (GitHub issue #405). Not every check needs an entry — a check that never calls
/// `.with_detail(...)` on the Rust side has nothing to render, and there's no reliable text-scan
/// way to derive that fact here (detail-emitting calls often live in a shared check-core helper
/// several files away from the concrete check, with the detail key passed as a variable rather
/// than a literal — see `region_size_check_core.rs`) — so `issueRegistry.ts` names that closed set
/// explicitly as `NO_DETAIL_CHECKS` instead. Ids in that set are excluded from the diff entirely
/// (not required to have a real, and not flagged if they don't) — everything else still needs a
/// real `DETAIL_LABELS`/`DETAIL_DESCRIPTIONS` entry.
pub fn find_missing_issue_registry(
    ids: &QualityIds,
    issue_registry_source: &str,
) -> Vec<MissingEntry> {
    let no_detail = no_detail_checks(issue_registry_source);
    let checked_ids: BTreeSet<String> = ids.check_ids.difference(&no_detail).cloned().collect();
    let mut missing = Vec::new();
    collect_missing(
        &mut missing,
        "DETAIL_LABELS",
        &checked_ids,
        issue_registry_source,
    );
    collect_missing(
        &mut missing,
        "DETAIL_DESCRIPTIONS",
        &checked_ids,
        issue_registry_source,
    );
    missing
}

/// Extracts the quoted ids inside `issueRegistry.ts`'s `const NO_DETAIL_CHECKS = [...]` array
/// literal — a plain text scan bounded by the array's own `[`/`]`, same spirit as
/// `collect_missing`'s object-literal scan. An absent `NO_DETAIL_CHECKS` (e.g. the const gets
/// renamed) degrades to an empty set, which makes `find_missing_issue_registry` fall back to
/// flagging every check id — the same "report nothing masks the real problem, but here the safer
/// default is the opposite" trade-off as `collect_missing`'s own absent-registry case, just
/// inverted: an accidentally-vanished allowlist should surface as new completeness failures, not
/// silently stop excluding ids.
fn no_detail_checks(source: &str) -> BTreeSet<String> {
    let mut ids = BTreeSet::new();
    let Some(const_start) = source.find("const NO_DETAIL_CHECKS") else {
        return ids;
    };
    let Some(open) = source[const_start..].find('[') else {
        return ids;
    };
    let array_start = const_start + open + 1;
    let Some(close) = source[array_start..].find(']') else {
        return ids;
    };
    let array_body = &source[array_start..array_start + close];
    for part in array_body.split(',') {
        let trimmed = part.trim().trim_matches('"');
        if !trimmed.is_empty() {
            ids.insert(trimmed.to_string());
        }
    }
    ids
}

/// Diffs `ids.check_ids` against the `qc_kind_registry!` table in `qc_kind_registry_source`
/// (`maze-runner/src/runner/qc_kind_registry.rs`, GitHub issue #407) — the single place every
/// registered check `type_id` must appear for the generated `check_kind_for_type`/`build_rule` to
/// be able to construct it (GitHub issue #405's original gap, now closed by generating both from
/// one table instead of hand-syncing them). A check id absent from this table can never be
/// selected by `config.checks`, the same class of silent gap `qualityI18n.ts`'s registries close
/// for the UI side.
pub fn find_missing_check_factory(
    ids: &QualityIds,
    qc_kind_registry_source: &str,
) -> Vec<MissingEntry> {
    let mut missing = Vec::new();
    // Anchored on a line-start `qc_kind_registry! {` (the macro *call*) rather than a bare
    // substring search — `macro_rules! qc_kind_registry { ... }` (the macro's own *definition*,
    // which appears earlier in the file and contains no id literals) doesn't match this anchor,
    // so a `.find("qc_kind_registry! {")` can't be fooled into landing there. A doc comment
    // mentioning the literal invocation text is a similar trap this anchor also avoids, as long
    // as the comment isn't itself at column 0 starting exactly with that text.
    let Some(invocation_start) = qc_kind_registry_source.find("\nqc_kind_registry! {") else {
        // Invocation itself not found — almost certainly renamed/moved, not that every entry was
        // deleted; report nothing rather than a wall of false positives masking the real problem.
        return missing;
    };
    let invocation_end = qc_kind_registry_source[invocation_start..]
        .find("\n}")
        .map(|i| invocation_start + i)
        .unwrap_or(qc_kind_registry_source.len());
    let invocation_body = &qc_kind_registry_source[invocation_start..invocation_end];
    for id in &ids.check_ids {
        let entry_present = invocation_body.contains(&format!("\"{id}\""));
        if !entry_present {
            missing.push(MissingEntry {
                registry: "qc_kind_registry",
                id: id.clone(),
            });
        }
    }
    missing
}

/// The paraglide message-key prefix each registry's entries are built from (`m["<prefix>.<id>.label"]`).
/// `None` for any registry `find_missing` doesn't call `collect_missing` with — kept as a lookup
/// miss rather than a panic so a future registry added on one side without the other degrades to
/// a skipped scaffold entry, not a runtime crash.
fn message_prefix_for(registry: &str) -> Option<&'static str> {
    match registry {
        "checkI18n" => Some("check"),
        "strategyI18n" => Some("strategy"),
        "issueI18n" => Some("issue"),
        "paramI18n" => Some("param"),
        _ => None,
    }
}

/// Appends a TODO-stub entry (`label: "TODO_<id>"`, `description: "TODO"`) to `qualityi18n_source`
/// for every id in `missing`, and matching `"<prefix>.<id>.label"`/`"<prefix>.<id>.description"`
/// TODO placeholder strings to both `en_source` and `ru_source` — so a fresh check/strategy/issue-
/// kind/param id gets a runnable entry shape immediately, and the author only has to replace the
/// placeholder text instead of retyping the entry/message-key structure from scratch. Same text-
/// scan approach as `find_missing`/`collect_missing`: insertion point is right after the last
/// existing entry for that registry (found by scanning for `"\n<prefix>.` occurrences), so the
/// stub lands in the same block a human would have added it to, keeping the diff readable.
pub fn scaffold(
    missing: &[MissingEntry],
    qualityi18n_source: &str,
    en_source: &str,
    ru_source: &str,
) -> (String, String, String) {
    let mut ts = qualityi18n_source.to_string();
    let mut en = en_source.to_string();
    let mut ru = ru_source.to_string();

    for m in missing {
        let Some(prefix) = message_prefix_for(m.registry) else {
            eprintln!(
                "codegen: --scaffold: no message-key prefix known for registry \"{}\" — skipped id \"{}\"",
                m.registry, m.id
            );
            continue;
        };
        ts = insert_ts_entry(&ts, m.registry, &m.id, prefix);
        en = insert_message_keys(&en, prefix, &m.id);
        ru = insert_message_keys(&ru, prefix, &m.id);
    }

    (ts, en, ru)
}

fn insert_ts_entry(source: &str, registry: &str, id: &str, prefix: &str) -> String {
    let Some(registry_start) = source.find(&format!("export const {registry}")) else {
        return source.to_string();
    };
    let Some(close_offset) = source[registry_start..].find("\n};") else {
        return source.to_string();
    };
    let insert_at = registry_start + close_offset + 1; // right before the closing "};" line
    let entry = format!(
        "  {id}: {{\n    label: m[\"{prefix}.{id}.label\"] as MessageFn,\n    description: m[\"{prefix}.{id}.description\"] as MessageFn,\n  }},\n"
    );
    let mut out = String::with_capacity(source.len() + entry.len());
    out.push_str(&source[..insert_at]);
    out.push_str(&entry);
    out.push_str(&source[insert_at..]);
    out
}

/// Inserts `"<prefix>.<id>.label"`/`"<prefix>.<id>.description"` TODO placeholders right after the
/// last existing `"<prefix>.` key, or right before the file's closing `}` if no such key exists yet.
fn insert_message_keys(source: &str, prefix: &str, id: &str) -> String {
    let marker = format!("\"{prefix}.");
    let insert_at = match source.rfind(&marker) {
        Some(last_key_start) => match source[last_key_start..].find('\n') {
            Some(rel_newline) => last_key_start + rel_newline + 1,
            None => source.len(),
        },
        None => match source.rfind('}') {
            Some(closing_brace) => closing_brace,
            None => source.len(),
        },
    };
    let entry = format!(
        "  \"{prefix}.{id}.label\": \"TODO_{id}\",\n  \"{prefix}.{id}.description\": \"TODO\",\n"
    );
    let mut out = String::with_capacity(source.len() + entry.len());
    out.push_str(&source[..insert_at]);
    out.push_str(&entry);
    out.push_str(&source[insert_at..]);
    out
}

