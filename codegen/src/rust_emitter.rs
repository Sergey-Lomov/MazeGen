//! Writes `<stem>_wire.rs` — `wire_tags`, `impl EncodeEventPayload`, `impl DebugEvent` — for one
//! `EventSource`. Never writes anywhere else (plan section 5's "явная граница записи"): the only
//! other file this module touches is the original enum's source file, and only to insert an
//! idempotent `mod` line (see `ensure_mod_declared`).

use crate::codecs;
use crate::golden::{self, GoldenEntry};
use crate::naming::{to_screaming_snake, to_snake_case};
use crate::schema::{EventSource, FieldType, MutatingMode, VariantShape};
use crate::type_map;

pub fn generate_rust_wire_file(source: &EventSource) -> String {
    let mut out = String::new();
    out.push_str("// @generated by codegen/ — DO NOT EDIT.\n");
    out.push_str(&format!("// Source enum: {} (in the sibling file). Do not hand-edit — see plan `toasty-honking-pie.md`.\n\n", source.enum_name));
    out.push_str(&format!("use super::{};\n", source.enum_name));
    emit_codec_imports(&mut out, source);
    out.push_str("use crate::event_log::wire_primitives::*;\n");
    out.push_str("use crate::event_log::{DebugEvent, EncodeEventPayload};\n");
    out.push('\n');

    emit_wire_tags(&mut out, source);
    emit_encode_impl(&mut out, source);
    emit_debug_event_impl(&mut out, source);
    emit_golden_tests(&mut out, source);
    out
}

/// Round-trip regression test (plan section 7) — "защита от регрессий, не от ошибок генератора"
/// (a wrong `Schema` produces a wrong golden entry the same way it produces wrong code, so this
/// doesn't independently prove correctness; the existing hand-written tests do that). Only
/// standard-type variants get an entry (see `golden` module doc) — a variant with a custom-coded
/// field has no entry here at all, not a placeholder.
fn emit_golden_tests(out: &mut String, source: &EventSource) {
    let entries = golden::generate_golden(source);
    if entries.is_empty() {
        return;
    }
    out.push_str("\n#[cfg(test)]\nmod golden_tests {\n    use super::*;\n\n");
    for GoldenEntry {
        variant_name,
        rust_construct_expr,
        expected_bytes,
        ..
    } in &entries
    {
        let test_name = format!("golden_round_trip_{}", to_snake_case(variant_name));
        out.push_str(&format!("    #[test]\n    fn {test_name}() {{\n"));
        out.push_str(&format!("        let event = {rust_construct_expr};\n"));
        out.push_str("        let mut bytes = Vec::new();\n");
        out.push_str("        event.encode_payload(&mut bytes);\n");
        let bytes_lit: Vec<String> = expected_bytes.iter().map(|b| b.to_string()).collect();
        out.push_str(&format!(
            "        assert_eq!(bytes, vec![{}]);\n",
            bytes_lit.join(", ")
        ));
        out.push_str("    }\n\n");
    }
    out.push_str("}\n");
}

/// Every distinct custom codec this source's variants reference gets a `use super::<fn>;` — the
/// hand-written write function lives in the enum's own file (a sibling module to `<stem>_wire.rs`
/// from the compiler's perspective, reached via `super::`), same as the enum itself.
fn emit_codec_imports(out: &mut String, source: &EventSource) {
    let mut seen = std::collections::BTreeSet::new();
    for v in &source.variants {
        let fields: Vec<&FieldType> = match &v.shape {
            VariantShape::Unit => vec![],
            VariantShape::NewtypeTuple(f) => vec![&f.ty],
            VariantShape::Struct(fields) => fields.iter().map(|f| &f.ty).collect(),
        };
        for ty in fields {
            if let FieldType::Custom(name) = ty
                && let Some(c) = codecs::lookup(name)
            {
                seen.insert(c.rust_write_fn);
            }
        }
    }
    for f in seen {
        out.push_str(&format!("use super::{f};\n"));
    }
}

fn emit_wire_tags(out: &mut String, source: &EventSource) {
    out.push_str("mod wire_tags {\n");
    for v in &source.variants {
        out.push_str(&format!(
            "    pub const {}: u16 = {};\n",
            to_screaming_snake(&v.name),
            v.tag
        ));
    }
    out.push_str("}\n\n");
}

fn emit_encode_impl(out: &mut String, source: &EventSource) {
    let name = &source.enum_name;
    out.push_str(&format!("impl EncodeEventPayload for {name} {{\n"));
    out.push_str("    fn type_id(&self) -> u16 {\n        match self {\n");
    for v in &source.variants {
        let pat = variant_pattern(&v.name, &v.shape, false);
        out.push_str(&format!(
            "            {name}::{pat} => wire_tags::{},\n",
            to_screaming_snake(&v.name)
        ));
    }
    out.push_str("        }\n    }\n\n");

    out.push_str("    fn encode_payload(&self, out: &mut Vec<u8>) {\n        match self {\n");
    for v in &source.variants {
        let pat = variant_pattern(&v.name, &v.shape, true);
        out.push_str(&format!("            {name}::{pat} => {{\n"));
        emit_field_writes(out, &v.shape);
        out.push_str("            }\n");
    }
    out.push_str("        }\n    }\n}\n\n");
}

fn emit_field_writes(out: &mut String, shape: &VariantShape) {
    match shape {
        VariantShape::Unit => {}
        VariantShape::NewtypeTuple(field) => {
            out.push_str(&format!(
                "                {}(out, {});\n",
                write_fn_for(&field.ty),
                field_ref("__field0", &field.ty)
            ));
        }
        VariantShape::Struct(fields) => {
            for f in fields {
                out.push_str(&format!(
                    "                {}(out, {});\n",
                    write_fn_for(&f.ty),
                    field_ref(&f.name, &f.ty)
                ));
            }
        }
    }
}

/// Copy standard types (`NodeId`/`u32`/`u64`/`usize`/`f64`/`bool`) are dereferenced (`*name`) —
/// the field is matched by reference (`match self { ... }`), so a Copy scalar needs deref to pass
/// by value into its `write_*` helper's `(out, T)` signature. Everything else — `String`,
/// `Vec<NodeId>`/`Vec<f64>`, `Option<NodeId>`/`Option<usize>` (whose helpers take the `Option<T>`
/// by value, not `&Option<T>` — an `Option<T>` is itself `Copy` whenever `T` is, so it also
/// derefs), and every custom-coded field — is passed as `name` (a reference into `self`), matching
/// each existing hand-written helper's own `&str`/`&[T]`/`&IssuePayload`-shaped signature.
fn field_ref(name: &str, ty: &FieldType) -> String {
    match ty {
        FieldType::Standard(t)
            if matches!(
                *t,
                "NodeId"
                    | "u32"
                    | "u64"
                    | "usize"
                    | "f64"
                    | "bool"
                    | "Option<NodeId>"
                    | "Option<usize>"
                    | "&'staticstr"
            ) =>
        {
            format!("*{name}")
        }
        _ => name.to_string(),
    }
}

fn write_fn_for(ty: &FieldType) -> &str {
    match ty {
        FieldType::Standard(t) => type_map::lookup(t)
            .map(|m| m.rust_write_fn)
            .unwrap_or("write_unknown"),
        FieldType::Custom(name) => codecs::lookup(name)
            .map(|c| c.rust_write_fn)
            .unwrap_or("write_unknown_custom"),
    }
}

fn emit_debug_event_impl(out: &mut String, source: &EventSource) {
    let name = &source.enum_name;
    out.push_str(&format!(
        "impl DebugEvent for {name} {{\n    fn is_mutating(&self) -> bool {{\n"
    ));
    match source.mutating_mode {
        MutatingMode::AlwaysMutating => out.push_str("        true\n"),
        MutatingMode::PerVariant => {
            let mutating: Vec<&str> = source
                .variants
                .iter()
                .filter(|v| v.mutating)
                .map(|v| v.name.as_str())
                .collect();
            if mutating.is_empty() {
                out.push_str("        false\n");
            } else {
                out.push_str("        matches!(\n            self,\n            ");
                let arms: Vec<String> = mutating
                    .iter()
                    .map(|n| {
                        let v = source.variants.iter().find(|v| v.name == *n).unwrap();
                        format!("{name}::{}", variant_pattern(n, &v.shape, false))
                    })
                    .collect();
                out.push_str(&arms.join("\n                | "));
                out.push_str("\n        )\n");
            }
        }
    }
    out.push_str("    }\n}\n");
}

fn variant_pattern(name: &str, shape: &VariantShape, bind: bool) -> String {
    match shape {
        VariantShape::Unit => name.to_string(),
        VariantShape::NewtypeTuple(_) => {
            if bind {
                format!("{name}(__field0)")
            } else {
                format!("{name}(..)")
            }
        }
        VariantShape::Struct(fields) => {
            if bind {
                let names: Vec<&str> = fields.iter().map(|f| f.name.as_str()).collect();
                format!("{name} {{ {} }}", names.join(", "))
            } else {
                format!("{name} {{ .. }}")
            }
        }
    }
}

/// Idempotently ensures the source file declares `mod <stem>_wire;` + a re-export — the only
/// permitted edit to a non-`_wire.rs` file (plan section 5). Returns the updated file text, or
/// `None` if the line was already present (caller skips the write in that case).
pub fn ensure_mod_declared(source_text: &str, stem: &str) -> Option<String> {
    // `#[path = "..."]` — the enum's own file is itself a submodule (e.g.
    // `generation::recursive_backtracker`), so a plain `mod x_wire;` would resolve relative to
    // `generation/recursive_backtracker/x_wire.rs` (Rust's module-tree convention for a
    // non-`mod.rs`/non-`lib.rs` file), not the sibling file `codegen` actually writes next to the
    // enum's own file. The explicit `#[path]` pins it to the sibling regardless of the enum's own
    // file's position in the module tree.
    //
    // No `use x_wire::*;` — the module's only contents are `impl` blocks (plus a private
    // `wire_tags` submodule), and `impl`s don't need importing to take effect once the trait
    // itself is in scope; a re-export here would just be an unused-import warning.
    let mod_line = format!("#[path = \"{stem}_wire.rs\"]\nmod {stem}_wire;");
    if source_text.contains(&format!("mod {stem}_wire;")) {
        return None;
    }
    Some(format!("{mod_line}\n\n{source_text}"))
}

#[cfg(test)]
mod ensure_mod_declared_tests {
    use super::*;

    #[test]
    fn inserts_the_path_and_mod_lines_above_existing_content_when_absent() {
        let source = "use crate::ids::NodeId;\n\npub enum Foo {}\n";
        let updated =
            ensure_mod_declared(source, "foo").expect("mod line was absent, should insert");
        assert_eq!(
            updated,
            "#[path = \"foo_wire.rs\"]\nmod foo_wire;\n\nuse crate::ids::NodeId;\n\npub enum Foo {}\n"
        );
    }

    #[test]
    fn returns_none_when_the_mod_line_is_already_present() {
        let source = "#[path = \"foo_wire.rs\"]\nmod foo_wire;\n\nuse crate::ids::NodeId;\n\npub enum Foo {}\n";
        assert!(ensure_mod_declared(source, "foo").is_none());
    }

    /// Regression guard for the idempotency contract `main.rs` relies on: calling this twice in a
    /// row (as a second `cargo run -p codegen` would) must never duplicate the `mod` line — the
    /// second call must return `None`, not a second inserted copy.
    #[test]
    fn a_second_call_on_its_own_output_is_a_no_op() {
        let source = "pub enum Foo {}\n";
        let once = ensure_mod_declared(source, "foo").expect("first call should insert");
        assert!(
            ensure_mod_declared(&once, "foo").is_none(),
            "second call must not insert a duplicate mod line"
        );
    }

    /// `mod {stem}_wire;` is matched as a substring anywhere in the file, not just at the top —
    /// pins down that a hand-written `mod foo_wire;` placed elsewhere in the source (however
    /// unlikely) still suppresses the insertion rather than producing two conflicting `mod`
    /// declarations that would fail to compile.
    #[test]
    fn detects_the_mod_line_even_if_it_appears_later_in_the_file() {
        let source = "pub enum Foo {}\n\nmod foo_wire;\n";
        assert!(ensure_mod_declared(source, "foo").is_none());
    }
}
