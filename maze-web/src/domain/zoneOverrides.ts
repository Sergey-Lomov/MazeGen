/** Generation parameters a zone override may set (GitHub issue #1038), by the wire key core reads. "Depth-first
 *  traversal" is absent on purpose: it picks the next cell to process, not the work done on one cell. */
export const ZONE_OVERRIDE_PARAM_KEYS = [
  "corridor_chance",
  "branching",
  "directionality",
  "cyclicity",
  "one_way_chance",
  "teleport_chance",
  "teleport_one_way_chance",
  "cross_floor_teleport_balance",
  "split_chance",
  "vertical_chance",
  "vertical_passage_elevator_balance",
  "one_way_vertical_passage_chance",
  "vertical_up_down_balance",
  "elevator_span_min",
  "elevator_span_max",
  "elevator_branching",
  "allow_non_consecutive_elevator_floors",
] as const satisfies readonly ZoneOverrideParamKey[];

/** The override parameters that are on/off switches: stored as 0 or 1 and sent to core as booleans. */
export const ZONE_OVERRIDE_SWITCH_KEYS: readonly ZoneOverrideParamKey[] = ["allow_non_consecutive_elevator_floors"];

/** What an override (of generation or of export parameters) points at. */
export type ZoneTargets = Pick<ZoneOverride, "zoneIds" | "groupIds">;

/** The ids of the zones an override reaches: its own zones plus the zones of its groups, in ascending id order. An id
 *  that names no zone (deleted, or an automatic zone that is not computed at the moment) is not counted. */
export function overrideZoneIds(override: ZoneTargets, zones: readonly Zone[], groups: readonly ZoneGroup[]): number[] {
  const existing = new Set(zones.map((zone) => zone.id));
  const ids = new Set<number>();
  for (const id of override.zoneIds) if (existing.has(id)) ids.add(id);
  for (const group of groups) {
    if (!override.groupIds.includes(group.id)) continue;
    for (const id of group.zoneIds) if (existing.has(id)) ids.add(id);
  }
  return [...ids].sort((a, b) => a - b);
}

/** The parameters an override sets, in `ZONE_OVERRIDE_PARAM_KEYS` order. */
export function overrideParamKeys(override: ZoneOverride): ZoneOverrideParamKey[] {
  return ZONE_OVERRIDE_PARAM_KEYS.filter((key) => override.params[key] !== undefined);
}

/** Whether any of the zones has a cell: what a feature bound to zones can act on. A zone with no cell, like a deleted one,
 *  gives it nothing (GitHub issue #1034: one meaning of "nothing there" for every consumer of zones). */
export function zonesHaveCells(ids: readonly number[], zones: readonly Zone[]): boolean {
  const wanted = new Set(ids);
  return zones.some((zone) => wanted.has(zone.id) && zone.cells.length > 0);
}

/** An override with nothing to act on: its zones were deleted or have no cells, and its groups hold no such zone. Nothing
 *  is generated by it. */
export function overrideHasNoZones(override: ZoneTargets, zones: readonly Zone[], groups: readonly ZoneGroup[]): boolean {
  return !zonesHaveCells(overrideZoneIds(override, zones, groups), zones);
}

/** Why an override has nothing to act on: what it points at is `missing` (deleted), or still there but `empty` (no cells).
 *  `null` for an override that reaches a cell. */
export function overrideProblem(override: ZoneTargets, zones: readonly Zone[], groups: readonly ZoneGroup[]): "missing" | "empty" | null {
  if (!overrideHasNoZones(override, zones, groups)) return null;
  const zoneExists = override.zoneIds.some((id) => zones.some((zone) => zone.id === id));
  const groupExists = groups.some((group) => override.groupIds.includes(group.id));
  return zoneExists || groupExists ? "empty" : "missing";
}

/** A parameter with a special value on an empty zone or group (`emptyParamTargets`): `path` is the parameter, `sample` the
 *  first override that sets it. */
export interface EmptyParamTargets<O> {
  key: string;
  path: string;
  sample: O;
  zoneIds: number[];
  groupIds: number[];
}

/** The zones and groups an override names that hold no cell: an existing zone without cells, an existing group none of
 *  whose zones has any. */
export function emptyOverrideTargets(override: ZoneTargets, zones: readonly Zone[], groups: readonly ZoneGroup[]): ZoneTargets {
  return {
    zoneIds: override.zoneIds.filter((id) => zones.some((zone) => zone.id === id && zone.cells.length === 0)),
    groupIds: override.groupIds.filter((id) => groups.some((group) => group.id === id && !zonesHaveCells(group.zoneIds, zones))),
  };
}

/** The parameters of the overrides that have nothing to act on because their zones or groups have no cells (not because
 *  they are gone), each with the empty zones and groups that carry its value. `keyOf` names a parameter of an override
 *  (the generation parameters are told apart by their key, the export ones also by their mode). */
export function emptyParamTargets<O extends ZoneTargets & { params: object }>(
  overrides: readonly O[],
  zones: readonly Zone[],
  groups: readonly ZoneGroup[],
  keyOf: (override: O, path: string) => string,
): EmptyParamTargets<O>[] {
  const byKey = new Map<string, { path: string; sample: O; zoneIds: Set<number>; groupIds: Set<number> }>();
  for (const override of overrides) {
    if (overrideProblem(override, zones, groups) !== "empty") continue;
    const empty = emptyOverrideTargets(override, zones, groups);
    for (const [path, value] of Object.entries(override.params)) {
      if (value === undefined) continue;
      const key = keyOf(override, path);
      const entry = byKey.get(key) ?? { path, sample: override, zoneIds: new Set<number>(), groupIds: new Set<number>() };
      empty.zoneIds.forEach((id) => entry.zoneIds.add(id));
      empty.groupIds.forEach((id) => entry.groupIds.add(id));
      byKey.set(key, entry);
    }
  }
  return [...byKey].map(([key, e]) => ({ key, path: e.path, sample: e.sample, zoneIds: [...e.zoneIds], groupIds: [...e.groupIds] }));
}

export interface ZoneOverrideConflict {
  /** The other override that sets the same parameters on the same cells. */
  otherId: number;
  /** The parameters both set on at least one common cell. */
  params: ZoneOverrideParamKey[];
}

/** Overrides that set the same parameter on a common cell, by override id. Overlapping zones are fine while they set
 *  different parameters; here the zone with the smaller id wins, which the user cannot see, so it is reported. */
export function zoneOverrideConflicts(overrides: readonly ZoneOverride[], zones: readonly Zone[], groups: readonly ZoneGroup[]): Map<number, ZoneOverrideConflict[]> {
  const cellsOfZone = zoneCellSets(zones);
  const reaches = overrides.map((override) => ({ override, zoneIds: overrideZoneIds(override, zones, groups), keys: overrideParamKeys(override) }));
  const result = new Map<number, ZoneOverrideConflict[]>();
  for (let i = 0; i < reaches.length; i++) {
    for (let j = i + 1; j < reaches.length; j++) {
      const a = reaches[i];
      const b = reaches[j];
      const shared = a.keys.filter((key) => b.keys.includes(key));
      if (shared.length === 0 || !zonesShareCell(a.zoneIds, b.zoneIds, cellsOfZone)) continue;
      result.set(a.override.id, [...(result.get(a.override.id) ?? []), { otherId: b.override.id, params: shared }]);
      result.set(b.override.id, [...(result.get(b.override.id) ?? []), { otherId: a.override.id, params: shared }]);
    }
  }
  return result;
}

/** Lazily built cell set of each zone by id; a cell is `encodePoint(x, y) * 64 + floor`. */
export function zoneCellSets(zones: readonly Zone[]): (id: number) => Set<number> {
  const zoneById = new Map(zones.map((zone) => [zone.id, zone]));
  const zoneCells = new Map<number, Set<number>>();
  return (id) => {
    let cells = zoneCells.get(id);
    if (!cells) {
      cells = new Set<number>();
      for (const [floor, x, y] of zoneById.get(id)?.cells ?? []) cells.add(encodePoint(x, y) * 64 + floor);
      zoneCells.set(id, cells);
    }
    return cells;
  };
}

export function zonesShareCell(first: readonly number[], second: readonly number[], cellsOf: (id: number) => Set<number>): boolean {
  for (const a of first) {
    const cellsA = cellsOf(a);
    if (cellsA.size === 0) continue;
    for (const b of second) {
      const cellsB = cellsOf(b);
      const [small, large] = cellsA.size <= cellsB.size ? [cellsA, cellsB] : [cellsB, cellsA];
      for (const cell of small) if (large.has(cell)) return true;
    }
  }
  return false;
}

/** How many warnings the overrides give (the bubbles of the generation warnings section): one for zones that are gone, one
 *  per parameter set on an empty zone or group, one for overlapping zones with their own values. */
export function zoneOverrideWarningCount(overrides: readonly ZoneOverride[], zones: readonly Zone[], groups: readonly ZoneGroup[]): number {
  const missing = overrides.some((o) => overrideProblem(o, zones, groups) === "missing");
  const conflicting = zoneOverrideConflicts(overrides, zones, groups).size > 0;
  return (missing ? 1 : 0) + emptyParamTargets(overrides, zones, groups, (_, path) => path).length + (conflicting ? 1 : 0);
}

/** `override` without the zone `id`; the same object when it did not name it. */
export function overrideWithoutZone<T extends ZoneTargets>(override: T, id: number): T {
  return override.zoneIds.includes(id) ? { ...override, zoneIds: override.zoneIds.filter((z) => z !== id) } : override;
}

/** `override` without the group `id`; the same object when it did not name it. */
export function overrideWithoutGroup<T extends ZoneTargets>(override: T, id: number): T {
  return override.groupIds.includes(id) ? { ...override, groupIds: override.groupIds.filter((g) => g !== id) } : override;
}

/** One zone's share of an override on the wire (mirrors Rust's `ZoneOverrideDto`); `cells` are `[floor, x, y]`. */
export interface ZoneOverrideWire {
  zone_id: number;
  cells: [number, number, number][];
  params: Partial<Record<Exclude<ZoneOverrideParamKey, "allow_non_consecutive_elevator_floors">, number>> & { allow_non_consecutive_elevator_floors?: boolean };
}

/** The wire form of an override's parameters: switches become booleans. */
function wireParams(params: ZoneOverride["params"]): ZoneOverrideWire["params"] {
  const { allow_non_consecutive_elevator_floors: floors, ...rest } = params;
  return floors === undefined ? rest : { ...rest, allow_non_consecutive_elevator_floors: floors !== 0 };
}

/** The overrides as per-zone wire entries: an override reaches each of its zones (own and through groups) with its
 *  parameters, so core's "smaller zone id wins" rule settles every overlap. `zones` should be cut to the field already
 *  (`filterZonesToField`). Overrides that set nothing, and zones left with no cells, are dropped. */
export function buildZoneOverrideWire(overrides: readonly ZoneOverride[], zones: readonly Zone[], groups: readonly ZoneGroup[]): ZoneOverrideWire[] {
  const zoneById = new Map(zones.map((zone) => [zone.id, zone]));
  const wire: ZoneOverrideWire[] = [];
  for (const override of overrides) {
    if (overrideParamKeys(override).length === 0) continue;
    for (const id of overrideZoneIds(override, zones, groups)) {
      const cells = zoneById.get(id)?.cells ?? [];
      if (cells.length > 0) wire.push({ zone_id: id, cells: cells.map(([f, x, y]) => [f, x, y]), params: wireParams(override.params) });
    }
  }
  return wire;
}

/** The parameters that have overlapping zones in at least one pair of overrides, in `ZONE_OVERRIDE_PARAM_KEYS` order. */
export function zoneOverrideConflictParams(conflicts: ReadonlyMap<number, readonly ZoneOverrideConflict[]>): ZoneOverrideParamKey[] {
  const found = new Set<ZoneOverrideParamKey>();
  for (const list of conflicts.values()) for (const conflict of list) for (const key of conflict.params) found.add(key);
  return ZONE_OVERRIDE_PARAM_KEYS.filter((key) => found.has(key));
}
